-- =====================================================================
-- Hiring tracker (page: /employmenthiringassignment)
-- Candidates, their 24-hour assignment clock, and interviewer reviews.
-- Admin only. Tables sit in the private "app" schema; the browser calls
-- exactly one function, public.hiring_api(method, path, body).
-- Safe to run again: it never touches existing rows.
-- =====================================================================

create table if not exists app.hiring_candidates (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 200),
  email       text check (email is null or char_length(email) <= 254),
  phone       text check (phone is null or char_length(phone) <= 40),
  role        text not null default 'Full Stack Developer' check (char_length(role) between 1 and 120),
  stage       text not null default 'applied'
              check (stage in ('applied','interview','assignment','office','offer','hired','rejected')),
  resume_url  text check (resume_url is null or (resume_url ~* '^https?://' and char_length(resume_url) <= 1000)),
  notes       text check (notes is null or char_length(notes) <= 5000),
  assignment_sent_at       timestamptz,
  assignment_submitted_at  timestamptz,
  created_by  bigint references app.users(id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists app.hiring_reviews (
  id             bigint generated by default as identity primary key,
  candidate_id   bigint not null references app.hiring_candidates(id) on delete cascade,
  stage          text not null check (stage in ('interview','assignment','office')),
  score          numeric(5,2) check (score is null or (score >= 0 and score <= 100)),
  recommendation text check (recommendation in ('yes','hold','no')),
  feedback       text check (feedback is null or char_length(feedback) <= 5000),
  reviewer_name  text,
  created_by     bigint references app.users(id) on delete set null,
  created_at     timestamptz not null default now()
);
create index if not exists hiring_reviews_candidate_idx on app.hiring_reviews (candidate_id);

-- Locked down like every other table here: no direct access from the browser.
alter table app.hiring_candidates enable row level security;
alter table app.hiring_reviews enable row level security;
revoke all on table app.hiring_candidates, app.hiring_reviews from public, anon, authenticated;

-- ---------- helpers (not callable from the browser) ----------
create or replace function app.hr_list() returns jsonb
language sql stable as $$
  select jsonb_build_object(
    'candidates', coalesce((select jsonb_agg(to_jsonb(c) order by c.created_at desc, c.id desc) from app.hiring_candidates c), '[]'::jsonb),
    'reviews',    coalesce((select jsonb_agg(to_jsonb(r) order by r.created_at desc, r.id desc) from app.hiring_reviews r), '[]'::jsonb)
  )
$$;

create or replace function app.hr_candidate_save(me app.users, cid bigint, body jsonb) returns jsonb
language plpgsql as $$
declare
  nm text := btrim(coalesce(body->>'name', ''));
  st text := coalesce(nullif(btrim(body->>'stage'), ''), 'applied');
  rl text := coalesce(nullif(btrim(body->>'role'), ''), 'Full Stack Developer');
  em text := nullif(btrim(coalesce(body->>'email', '')), '');
  ph text := nullif(btrim(coalesce(body->>'phone', '')), '');
  ru text := nullif(btrim(coalesce(body->>'resume_url', '')), '');
  nt text := nullif(btrim(coalesce(body->>'notes', '')), '');
  row_ app.hiring_candidates;
begin
  if nm = '' then perform app.fail(400, 'Name is required.'); end if;
  if char_length(nm) > 200 then perform app.fail(400, 'Name must be 200 characters or fewer.'); end if;
  if char_length(rl) > 120 then perform app.fail(400, 'Role must be 120 characters or fewer.'); end if;
  if em is not null and char_length(em) > 254 then perform app.fail(400, 'Email is too long.'); end if;
  if ph is not null and char_length(ph) > 40 then perform app.fail(400, 'Phone is too long.'); end if;
  if nt is not null and char_length(nt) > 5000 then perform app.fail(400, 'Notes must be 5000 characters or fewer.'); end if;
  if st not in ('applied','interview','assignment','office','offer','hired','rejected') then
    perform app.fail(400, 'Unknown stage.');
  end if;
  if ru is not null and (ru !~* '^https?://' or char_length(ru) > 1000) then
    perform app.fail(400, 'Resume link must start with http:// or https:// and be under 1000 characters.');
  end if;

  if cid is null then
    insert into app.hiring_candidates (name, email, phone, role, stage, resume_url, notes, created_by)
    values (nm, em, ph, rl, st, ru, nt, me.id)
    returning * into row_;
  else
    update app.hiring_candidates
       set name = nm, email = em, phone = ph, role = rl, stage = st, resume_url = ru, notes = nt, updated_at = now()
     where id = cid
    returning * into row_;
    if row_.id is null then perform app.fail(404, 'Candidate not found.'); end if;
  end if;
  return to_jsonb(row_);
end $$;

create or replace function app.hr_candidate_delete(cid bigint) returns jsonb
language plpgsql as $$
begin
  delete from app.hiring_candidates where id = cid;
  if not found then perform app.fail(404, 'Candidate not found.'); end if;
  return jsonb_build_object('ok', true);
end $$;

-- The 24-hour clock uses the database's time, not the browser's.
create or replace function app.hr_assignment(cid bigint, body jsonb) returns jsonb
language plpgsql as $$
declare act text := coalesce(body->>'action', ''); row_ app.hiring_candidates;
begin
  select * into row_ from app.hiring_candidates where id = cid;
  if row_.id is null then perform app.fail(404, 'Candidate not found.'); end if;
  if act = 'sent' then
    update app.hiring_candidates
       set assignment_sent_at = now(), assignment_submitted_at = null, stage = 'assignment', updated_at = now()
     where id = cid returning * into row_;
  elsif act = 'submitted' then
    if row_.assignment_sent_at is null then perform app.fail(400, 'Mark the assignment as sent first.'); end if;
    update app.hiring_candidates set assignment_submitted_at = now(), updated_at = now()
     where id = cid returning * into row_;
  elsif act = 'reset' then
    update app.hiring_candidates set assignment_sent_at = null, assignment_submitted_at = null, updated_at = now()
     where id = cid returning * into row_;
  else
    perform app.fail(400, 'Unknown assignment action.');
  end if;
  return to_jsonb(row_);
end $$;

create or replace function app.hr_review_add(me app.users, cid bigint, body jsonb) returns jsonb
language plpgsql as $$
declare
  st text := coalesce(body->>'stage', '');
  rec text := coalesce(body->>'recommendation', '');
  raw text := nullif(btrim(coalesce(body->>'score', '')), '');
  fb text := nullif(btrim(coalesce(body->>'feedback', '')), '');
  sc numeric;
  row_ app.hiring_reviews;
begin
  if not exists (select 1 from app.hiring_candidates where id = cid) then perform app.fail(404, 'Candidate not found.'); end if;
  if st not in ('interview','assignment','office') then perform app.fail(400, 'Choose interview, assignment or office round.'); end if;
  if rec not in ('yes','hold','no') then perform app.fail(400, 'Choose Yes, Hold or No.'); end if;
  if raw is not null then
    if raw !~ '^\d{1,3}(\.\d{1,2})?$' then perform app.fail(400, 'Score must be a number from 0 to 100.'); end if;
    sc := raw::numeric;
    if sc > 100 then perform app.fail(400, 'Score must be a number from 0 to 100.'); end if;
  end if;
  if fb is not null and char_length(fb) > 5000 then perform app.fail(400, 'Feedback must be 5000 characters or fewer.'); end if;
  insert into app.hiring_reviews (candidate_id, stage, score, recommendation, feedback, reviewer_name, created_by)
  values (cid, st, sc, rec, fb, me.name, me.id)
  returning * into row_;
  return to_jsonb(row_);
end $$;

create or replace function app.hr_review_delete(rid bigint) returns jsonb
language plpgsql as $$
begin
  delete from app.hiring_reviews where id = rid;
  if not found then perform app.fail(404, 'Review not found.'); end if;
  return jsonb_build_object('ok', true);
end $$;

-- ---------- the one function the page calls ----------
create or replace function public.hiring_api(method text, path text, body jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = app, extensions, public as $$
declare
  me app.users; m text := upper(coalesce(method, 'GET')); p text := split_part(coalesce(path, ''), '?', 1); id bigint;
begin
  me := app.current_person();
  perform app.require_admin(me);
  body := coalesce(body, '{}'::jsonb);
  if p ~ '/\d+(/|$)' then id := substring(p from '/(\d+)(?:/|$)')::bigint; end if;

  if m = 'GET' and p = '/candidates' then return app.hr_list();
  elsif m = 'POST' and p = '/candidates' then return app.hr_candidate_save(me, null, body);
  elsif m = 'PATCH' and p ~ '^/candidates/\d+$' then return app.hr_candidate_save(me, id, body);
  elsif m = 'DELETE' and p ~ '^/candidates/\d+$' then return app.hr_candidate_delete(id);
  elsif m = 'POST' and p ~ '^/candidates/\d+/assignment$' then return app.hr_assignment(id, body);
  elsif m = 'POST' and p ~ '^/candidates/\d+/reviews$' then return app.hr_review_add(me, id, body);
  elsif m = 'DELETE' and p ~ '^/reviews/\d+$' then return app.hr_review_delete(id);
  end if;
  perform app.fail(404, 'Not found.');
  return null;
end $$;

-- ---------- permissions (same pattern as 06_api.sql and 07_owner.sql) ----------
revoke execute on all functions in schema app from public, anon, authenticated;
grant execute on function app.storage_can_write(text), app.storage_can_read(text), app.storage_can_delete(text) to authenticated;
revoke execute on function public.hiring_api(text, text, jsonb) from public, anon;
grant execute on function public.hiring_api(text, text, jsonb) to authenticated;
